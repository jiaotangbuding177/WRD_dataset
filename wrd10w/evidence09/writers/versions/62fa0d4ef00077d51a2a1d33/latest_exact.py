def build_prompt(n, lines, extras, prompt):
    parts = [PREFIX, "", "第%d页。图片中必须准确清晰显示以下画面文字（标题与关键词逐字一致，不得错字、漏字）：" % n]
    for ln in lines:
        parts.append(ln)
    for tag, txt in extras:
        parts.append("%s：%s" % (tag, txt))
    parts.append("")
    parts.append("画面描述：" + prompt)
    return "\n".join(parts)

def main():
    only = sys.argv[1:] if len(sys.argv) > 1 else None
    failed = []
    for n, lines, extras, prompt in PAGES:
        if only and str(n) not in only:
            continue
        out = os.path.join(OUT, "第%d页.png" % n)
        if os.path.exists(out) and os.path.getsize(out) > 100000:
            print("[skip] 第%d页 已存在" % n, flush=True)
            continue
        full = build_prompt(n, lines, extras, prompt)
        ok = False
        for attempt in (1, 2):
            r = subprocess.run(TOOL + ["--text", full, "--output", out],
                               capture_output=True, text=True, timeout=900)
            print("[page %d attempt %d] rc=%s" % (n, attempt, r.returncode), flush=True)
            if r.returncode == 0 and os.path.exists(out) and os.path.getsize(out) > 100000:
                ok = True
                break
            print(r.stdout[-500:], r.stderr[-500:], flush=True)
            time.sleep(5)
        if not ok:
            failed.append(n)
            print("[FAIL] 第%d页" % n, flush=True)
    print("DONE failed=%s" % failed, flush=True)

if __name__ == "__main__":
    main()
