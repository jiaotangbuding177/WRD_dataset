def set_east(run, name='宋体'):
    run.font.name = 'Calibri'
    rpr = run._element.get_or_add_rPr()
    rpr.rFonts.set(qn('w:eastAsia'), name)

def para(doc, text, bold=False, size=10.5, space_after=4):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(size)
    set_east(r)
    p.paragraph_format.space_after = Pt(space_after)
    return p

def heading(doc, text, size=13):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(size)
    r.font.color.rgb = RGBColor(0x1F, 0x3B, 0x63)
    set_east(r, '微软雅黑')
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(6)
    return p

def table(doc, headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ''
        r = hdr[i].paragraphs[0].add_run(h)
        r.bold = True
        r.font.size = Pt(10)
        set_east(r)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            r = cells[i].paragraphs[0].add_run(str(v))
            r.font.size = Pt(9.5)
            set_east(r)
    doc.add_paragraph()
    return t

def base_doc(title, subtitle):
    doc = Document()
    st = doc.styles['Normal']
    st.font.size = Pt(10.5)
    st.font.name = 'Calibri'
    st.element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), '宋体')
    p = doc.add_paragraph()
    r = p.add_run(title)
    r.bold = True
    r.font.size = Pt(18)
    set_east(r, '微软雅黑')
    p.alignment = 1
    p2 = doc.add_paragraph()
    r2 = p2.add_run(subtitle)
    r2.font.size = Pt(11)
    r2.bold = True
    set_east(r2, '微软雅黑')
    p2.alignment = 1
    doc.add_paragraph()
    return doc

